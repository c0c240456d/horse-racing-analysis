
import streamlit as st


def show_glossary():
    st.title("📖 初心者向け競馬用語集")
    st.write(
        "競馬を初めて見る方でも理解できるように、"
        "基本的な用語を紹介します。"
    )

    st.divider()

    st.subheader("🐎 競馬の基本用語")

    terms = {
        "脚質": "馬のレース中の走り方や位置取りの特徴です。逃げ・先行・差し・追い込みの4種類があります。",

        "逃げ": "レースの最初から先頭に立ち、そのまま逃げ切ることを目指す走り方です。",

        "先行": "先頭集団の近くにつけてレースを進める走り方です。",

        "差し": "レースの前半は中団や後方に位置し、最後に前の馬を追い抜く走り方です。",

        "追い込み": "レースの前半は後方に位置し、最後に一気に追い上げる走り方です。",

        "上がり3ハロン": "レースの最後の600mを走るのにかかったタイムです。最後の脚の速さを判断する目安になります。",

        "単勝": "1着になる馬を予想する馬券です。",

        "複勝": "選んだ馬が3着以内に入ることを予想する馬券です。",

        "オッズ": "馬券の払戻金の倍率を表す数字です。一般的に倍率が高いほど人気が低い傾向があります。",

        "馬場状態": """
レースを行うコースの水分量や状態を表します。
主に4種類に分けられます。

・良（りょう）：水分が少なく、走りやすい状態

・稍重（ややおも）：少し水分を含んでいる状態

・重（おも）：水分が多く、ぬかるんでいる状態

・不良（ふりょう）：水分が非常に多く、かなりぬかるんでいる状態
"""
    }

    for term, explanation in terms.items():
        with st.expander(f"📌 {term}"):
            st.write(explanation)

    st.divider()

    st.info("分からない用語をクリックすると、説明を確認できます。")
